import type { AxialAnalysis } from "@/lib/bridge-preview";
import styles from "./ftl-upload.module.css";
import { SizingContext } from "./sizing-context";

const states = { tension: "Tração", compression: "Compressão", zero: "Nulo", mixed: "Misto" };
const number = (n: number) => new Intl.NumberFormat("pt-BR", { maximumFractionDigits: 3 }).format(n);

export function AxialResults({ analysis }: { analysis: AxialAnalysis }) {
  return (
    <section aria-labelledby="analysis-title" className={styles.analysis}>
      <h3 id="analysis-title">Resultados da análise</h3>
      <SizingContext analysis={analysis} />
      {analysis.charts.map((chart) => (
        <figure key={chart.id} className={styles.chart}>
          <h4>{chart.title}</h4>
          {/* SVG generated by our Python plotters; preserve the notebook rendering. */}
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img src={chart.image} alt={chart.title} />
          <figcaption>
            {chart.id === "axial" && "Forças em N e coordenadas em cm. Positivo: tração; negativo: compressão."}
            {chart.id === "displacement" && "Origem local da ponte e eixos em cm. A escala visual e o deslocamento máximo real em mm estão indicados no gráfico."}
            {chart.id === "sticks" && `Total: ${analysis.stick_counts.total_physical_sticks} palitos físicos e ${analysis.stick_counts.total_required_layers} camadas somadas entre as barras.`}
          </figcaption>
          <a href={chart.image} download={`${chart.id}.svg`}>Baixar gráfico SVG</a>
        </figure>
      ))}
      <details>
      <summary>Ver valores numéricos e reações</summary>
      <p>Esforço axial positivo indica tração; negativo indica compressão.</p>
      <div className={styles.tableScroll} tabIndex={0} role="region" aria-label="Esforços por barra">
        <table>
          <caption>Esforços axiais por barra</caption>
          <thead><tr><th>Barra</th><th>ID FTool</th><th>Comprimento (cm)</th><th>Esforço médio (N)</th><th>Estado</th></tr></thead>
          <tbody>{analysis.members.map((member) => <tr key={member.id}>
            <th scope="row">{member.id}</th><td>{member.ftool_id}</td><td>{number(member.length * 100)}</td>
            <td>{number(member.axial_force.average)}</td><td>{states[member.axial_force.state]}</td>
          </tr>)}</tbody>
        </table>
      </div>
      <div className={styles.tableScroll} tabIndex={0} role="region" aria-label="Reações de apoio">
        <table>
          <caption>Reações de apoio</caption>
          <thead><tr><th>Nó</th><th>Fx (N)</th><th>Fy (N)</th><th>Momento (N·m)</th></tr></thead>
          <tbody>{analysis.reactions.map((reaction) => <tr key={reaction.node}>
            <th scope="row">{reaction.node}</th><td>{number(reaction.fx)}</td><td>{number(reaction.fy)}</td><td>{number(reaction.moment)}</td>
          </tr>)}</tbody>
        </table>
      </div>
      </details>
    </section>
  );
}
